"""S0-02: migraciones reversibles y sin deriva respecto a los modelos."""

from __future__ import annotations

import os
import uuid
from collections.abc import Iterator

import asyncpg
import pytest
from alembic.util.exc import AutogenerateDiffsDetected

from deken_api.testing import run_alembic, run_sync

pytestmark = pytest.mark.integration


@pytest.fixture
def scratch_database() -> Iterator[str]:
    base = os.environ["DEKEN_TEST_DATABASE_URL"]
    plain = base.replace("postgresql+asyncpg://", "postgresql://")
    name = f"deken_mig_{uuid.uuid4().hex[:8]}"

    async def admin(sql: str) -> None:
        conn = await asyncpg.connect(plain)
        try:
            await conn.execute(sql)
        finally:
            await conn.close()

    run_sync(admin(f'CREATE DATABASE "{name}"'))
    yield f"{base.rpartition('/')[0]}/{name}"
    run_sync(admin(f'DROP DATABASE IF EXISTS "{name}" WITH (FORCE)'))


async def _tables(url: str) -> set[str]:
    conn = await asyncpg.connect(url.replace("postgresql+asyncpg://", "postgresql://"))
    try:
        rows = await conn.fetch("SELECT tablename FROM pg_tables WHERE schemaname = 'public'")
    finally:
        await conn.close()
    return {r["tablename"] for r in rows}


def test_upgrade_downgrade_upgrade_and_no_drift(scratch_database: str) -> None:
    run_alembic(scratch_database, "upgrade", "head")
    tables = run_sync(_tables(scratch_database))
    assert {"users", "user_sessions", "audit_events", "workers", "jobs"} <= tables

    run_alembic(scratch_database, "downgrade", "base")
    assert run_sync(_tables(scratch_database)) == {"alembic_version"}

    run_alembic(scratch_database, "upgrade", "head")
    try:
        run_alembic(scratch_database, "check")
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - mensaje útil si falla
        pytest.fail(f"Los modelos y las migraciones no coinciden: {exc}")
